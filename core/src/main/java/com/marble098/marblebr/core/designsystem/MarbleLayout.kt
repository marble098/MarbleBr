package com.marble098.marblebr.core.designsystem

import androidx.compose.ui.unit.dp

/**
 * ریتم چیدمانِ مشترکِ MarbleBr.
 *
 * چرا یک منبعِ واحد؟ پیش‌تر هر صفحه فاصله‌ها و اندازه‌های خودش را داشت (۱۶، ۱۸، ۹، ۱۰ و ۱۲
 * همه با هم در یک صفحه دیده می‌شد) و نتیجه‌اش این بود که کاشی‌های «میانبر» هم‌اندازه نبودند و
 * لبه‌های چپ/راست ردیف‌های مختلف با هم نمی‌خواندند. همهٔ صفحه‌ها از این ثابت‌ها استفاده می‌کنند تا:
 * - فاصلهٔ کناره‌ها در **همهٔ** بخش‌ها یکی باشد ([Screen]),
 * - فاصلهٔ بین کارت‌ها همیشه یک عدد باشد ([Gap] / [SectionGap]),
 * - همهٔ کاشی‌ها ارتفاعِ ثابت و هم‌اندازه داشته باشند ([TileHeight], [ShortcutHeight]).
 */
object MarbleLayout {
    /** فاصلهٔ افقیِ استاندارد از لبه‌های صفحه. */
    val Screen = 16.dp

    /** فاصلهٔ بین کارت‌ها و کاشی‌های یک شبکه. */
    val Gap = 10.dp

    /** فاصلهٔ بین بخش‌های مستقلِ یک صفحهٔ اسکرول‌شدنی. */
    val SectionGap = 14.dp

    /** فاصلهٔ کوچک و درونی (آیکن تا متن، چیپ‌ها). */
    val Inner = 8.dp

    /** ارتفاعِ ثابتِ کاشی‌های میان‌برِ صفحهٔ خانه. */
    val TileHeight = 86.dp

    /** ارتفاعِ ثابتِ کاشی‌های شبکهٔ شیتِ «میان‌برهای سریع». */
    val QuickTileHeight = 84.dp

    /** ارتفاعِ ثابتِ کارتِ نشان‌های صفحهٔ خانه (شبکهٔ دو ستونی). */
    val ShortcutHeight = 100.dp

    /** ارتفاعِ ثابتِ ردیفِ بازدیدهای اخیر. */
    val RecentRowHeight = 54.dp

    /** شعاع گوشهٔ کارت‌های اصلی. */
    val CardCorner = 20.dp

    /** شعاع گوشهٔ کاشی‌های کوچک. */
    val TileCorner = 18.dp
}
